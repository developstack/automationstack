/**
 * 执行台右栏（用例详情面板）的排版口径：区块标题一套、说明性正文一套。
 *
 * ## 为什么要收敛成常量
 *
 * 这一栏是由五六个互相独立的文件拼出来的（抬头 / 执行结论 / 前置条件 / 步骤 /
 * 判定记录），每个文件各自写 `text-sm` 还是 `text-xs`、要不要
 * `text-muted-foreground`。结果是同一屏上「快捷键提示」是 xs、「本条用例有步骤」
 * 是 sm、「最后由 X 判定为 Y」是 xs、附件空态又是 xs——用户的原话是同一件事说了
 * 三遍：执行结论要统一、判定记录要统一、元信息行要统一。逐处打补丁只会让下一个
 * 新增的区块再漂一次，所以把口径本身提出来，各处只引用、不再自己拼。
 *
 * ## 两档，不是三档
 *
 * 只有「标题」和「说明性正文」两档。之所以不再留一档 `text-xs` 做次要信息：
 * 这一栏本来就窄（右栏），xs 与 sm 在这个宽度下的区别读者感知不到层级，只感知到
 * 「这两行为什么不一样大」。层次仍然有，靠的是颜色（前景 / muted）与位置，
 * 不再靠字号——步骤卡片内部是唯一的例外，那里「预期」确实要比「步骤」小一号
 * （用户明确要求），那一处的 `text-xs` 写在 `run-step-card.tsx` 与
 * `step-reason-note.tsx` 里，属于卡片内部的层级，不走这里的面板级口径。
 *
 * ## 一处有意的偏离
 *
 * 用户**自己填**的说明正文（`run-verdict-comment.tsx` 里那段 `whitespace-pre-wrap`
 * 的失败描述）不套 `RUN_SECTION_TEXT`：它是内容，不是平台文字。把人写的复现步骤
 * 压成次要灰色是实打实的可读性回退，「颜色统一」要统一的是标签与元信息这类
 * 平台自己说的话。
 */

/** 区块标题：执行结论 / 前置条件 / 步骤与判定 / 判定记录，四处同一种。 */
export const RUN_SECTION_TITLE = "font-medium text-sm";

/** 区块内的说明性正文与元信息：字号与颜色都由这一条给。 */
export const RUN_SECTION_TEXT = "text-muted-foreground text-sm";
